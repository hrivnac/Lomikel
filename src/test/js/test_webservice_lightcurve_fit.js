'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../../webservice');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const host=read('graph.css'),plot=read('d3/lightcurve.css'),renderer=read('d3/lightcurve.js');
assert.match(host,/body\.workspace #plot\.ws-lightcurve\s*\{[^}]*height:\s*100%/);
assert.match(host,/iframe\[name\^="wsLightCurve-"\][^{]*\{[^}]*height:\s*100%/);
assert.match(plot,/#lightcurve-view\s*\{[^}]*height:\s*100%[^}]*display:\s*flex/s);
assert.match(plot,/#lightcurve-chart\s*\{[^}]*flex:\s*1/);
assert.match(renderer,/area\.clientHeight/);
assert.match(renderer,/addEventListener\('resize'/);
assert.match(renderer,/ResizeObserver/);
assert.match(read('workspace.js'),/lightcurveGraphState\.resize\(\)/);
assert.match(read('lightcurve-graph.js'),/lightCurveResize/);
assert.match(read('GraphView.jsp'),/lightcurve-graph\.js\?v=lightcurve-fit-/);
assert.match(read('index.jsp'),/graph\.css\?v=corr-fit-/);
assert.match(read('d3/lightcurve.jsp'),/lightcurve\.(?:css|js)\?v=lightcurve-fit-/);
console.log('LightCurve uses the full Plot pane and redraws on resize');
