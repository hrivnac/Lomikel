'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '../../webservice');
const graph = fs.readFileSync(path.join(root, 'graph.css'), 'utf8');
const css = fs.readFileSync(path.join(root, 'd3/skyview.css'), 'utf8');
const jsp = fs.readFileSync(path.join(root, 'd3/skyview.jsp'), 'utf8');
const code = fs.readFileSync(path.join(root, 'd3/skyview.js'), 'utf8');
const rootWindow = {};
vm.runInNewContext(code, {window:rootWindow, document:{getElementById:()=>null}});
assert.match(graph, /#skyview\s*\{[^}]*height:\s*100%/);
assert.match(graph, /iframe\[name="skyGraphFrame"\]\s*\{[^}]*height:\s*100%/);
assert.match(css, /#celestial-map\s*\{[^}]*min-width:\s*0/);
assert.match(css, /body\s*\{[^}]*display:\s*flex/);
assert.match(jsp, /skyview\.css\?v=skyview-3/);
assert.match(jsp, /skyview\.js\?v=skyview-5/);
assert.match(code, /formFields:\s*\{download:\s*true\}/);
assert.match(code, /controls:\s*true/);
assert.match(jsp, /<% if \(errorMessage == null\) \{ %><button type="button" id="sky-settings-toggle"/);
assert.match(css, /#celestial-form \.col:not\(#download\)/);
assert.match(css, /\.sky-settings-open #celestial-form/);
assert.match(code, /sky-settings-toggle/);
assert.equal(rootWindow.skyFitWidth(680, 500), 646, 'fill available width on a tall pane');
assert.equal(rootWindow.skyFitWidth(680, 220), 424, 'fit the whole map into a short pane');
assert.match(code, /ResizeObserver/);
assert.match(code, /root\.skyResizeObserver\s*=/);
assert.match(code, /sky-coordinates['"]\)\.addEventListener\('toggle'/);
assert.match(code, /skyResizeObserver\.observe\(root\.frameElement\)/);
assert.match(code, /sky-coordinates['"]\)\.addEventListener\('toggle',\s*resizeMap\)/);
assert.match(code, /root\.addEventListener\('resize',\s*resizeMap\)/);
assert.match(css, /#celestial-map canvas\s*\{[^}]*height:\s*auto!important/);
console.log('SkyView fills pane and fits map/controls without body scroll');
