'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../../webservice');
const endpoint = fs.readFileSync(path.join(root, 'SkyPositions.jsp'), 'utf8');
assert.match(endpoint, /mget\("ztf", "radec"/);
assert.match(endpoint, /mget\("lsst", "dia_radec"/);
assert.match(endpoint, /mget\("lsst", "ss_radec"/);
assert.match(endpoint, /"\/_mget"/);
assert.match(endpoint, /"_source"/);
assert.match(endpoint, /"location"/);
assert.match(endpoint, /MAX_OBJECTS\s*=\s*500/);
assert.match(endpoint, /MAX_POINTS/);
assert.match(endpoint, /requested\.contains/);
assert.match(endpoint, /setConnectTimeout/);
assert.match(endpoint, /setReadTimeout/);
assert.match(endpoint, /setInstanceFollowRedirects\(false\)/);
assert.match(endpoint, /Cache-Control/);
assert.doesNotMatch(endpoint, /request\.getParameter\("(?:url|host|index)"\)/);
const page = fs.readFileSync(path.join(root,'d3/skyview.jsp'),'utf8');
assert.match(page,/skyview\.js\?v=skyview-2/);
assert.match(page,/\\u003c/);
console.log('SkyView proxy and renderer packaging contracts passed');
