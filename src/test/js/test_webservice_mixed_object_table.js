'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'../..');
const jsp=fs.readFileSync(path.join(root,'ws/Nodes.jsp'),'utf8');
const tableScript=jsp.match(/<script type="text\/javascript">([\s\S]*?)<\/script>/)[1];
const originCode=()=>fs.readFileSync(path.join(root,'webservice/graph-table-origin.js'),'utf8');
const ztf={type:'vertex',label:'object',id:1,element:[{key:'objectId',value:'ZTF17aabgsqa'}]};
const lsst={type:'vertex',label:'object',id:2,element:[{key:'objectId',value:'313761043604045880'}]};
function fixture(useOrigin,graph){
 const nodes=[];
 const edges=[];
 const queries=[];
 const ctx={nodes,edges,server:'ztf-server',gr:'g',plotTableEscape:s=>s,findObjectByKey:(xs,key,id)=>xs.find(x=>x[key]===id),console};
 ctx.show=elements=>{if(elements)elements.forEach(v=>{
   if(v.type==='vertex'&&!nodes.some(n=>n.id===v.id))nodes.push({id:v.id,title:'object:'+v.element.find(p=>p.key==='objectId').value});
   if(v.type==='edge'&&!edges.some(e=>e.id===v.id))edges.push({id:v.id,from:v.outVid,to:v.inVid});
 });};
 ctx.disposeGraphView=()=>{nodes.length=0;edges.length=0};
 ctx.callGremlinValues=(request,selectedServer)=>{
   const id=Number(request.match(/\.V\('([0-9]+)'\)/)?.[1]);
   const matching=id===ztf.id?ztf:lsst;
   const expected=matching===ztf?'ztf-server':'lsst-server';
   queries.push({id,server:selectedServer||ctx.server});
   if(selectedServer)ctx.server=selectedServer; // legacy callGremlinValues mutates global server
   if ((selectedServer||ctx.server)!==expected) return [];
   const oid=matching.element[0].value;
   return ['[lbl:[object], objectId:['+oid+']]'];
 };
 ctx.window=ctx;
 vm.createContext(ctx);
 if(useOrigin)vm.runInContext(originCode(),ctx);
 graph.forEach(([server,vertex])=>{ctx.server=server;ctx.show([vertex])});
 function table(){vm.runInContext(tableScript.replace('<%=id%>',String(graph.at(-1)[1].id)),ctx);return ctx.tdata}
 return {ctx,queries,table};
}
assert.equal(fixture(false,[['ztf-server',ztf]]).table().length,1);
assert.equal(fixture(false,[['lsst-server',lsst]]).table().length,1);
const broken=fixture(false,[['ztf-server',ztf],['lsst-server',lsst]]);
assert.throws(()=>broken.table(),/substring|undefined/,'legacy table fails when it queries both vertex IDs on the current server');
const fixed=fixture(true,[['ztf-server',ztf],['lsst-server',lsst]]);
const rows=fixed.table();
assert.equal(rows.length,2);
assert.deepEqual(Array.from(rows,r=>r.objectId),['ZTF17aabgsqa','313761043604045880']);
assert.deepEqual(fixed.queries,[{id:1,server:'ztf-server'},{id:2,server:'lsst-server'}]);
assert.equal(fixed.ctx.server,'lsst-server','table lookup must restore the selected graph server');
fixed.ctx.callGremlinValues("g.V('1').valueMap().next().toString()",'explicit-server');
assert.equal(fixed.queries.at(-1).server,'explicit-server','an explicit server must not be rewritten');
fixed.ctx.nodes.splice(0,1);
fixed.ctx.show(null);
assert.equal(fixed.ctx.graphTableServerForVertex(ztf.id),null,'removed vertices lose their origin');
fixed.ctx.server='new-ztf-server';
fixed.ctx.show([ztf]);
assert.equal(fixed.ctx.graphTableServerForVertex(ztf.id),'new-ztf-server','re-added IDs adopt their new origin');
const changed=fixture(true,[['lsst-server',lsst],['ztf-server',ztf]]);
assert.equal(changed.table().length,2,'order of adding surveys must not matter');
changed.ctx.disposeGraphView();
assert.equal(changed.ctx.graphTableServerForVertex(ztf.id),null,'Reset removes stale origins');
const collision=fixture(true,[['ztf-server',ztf]]);
const differentObject={...lsst,id:1};
collision.ctx.server='lsst-server';
assert.throws(()=>collision.ctx.show([differentObject]),/Conflicting vertex ID/);
assert.equal(collision.ctx.nodes.length,1,'a collision must reject the whole incoming graph before legacy deduplication');
assert.equal(collision.ctx.nodes[0].title,'object:ZTF17aabgsqa');
assert.equal(collision.ctx.graphTableServerForVertex(1),'ztf-server');
assert.throws(()=>collision.ctx.show([lsst,differentObject]),/Conflicting vertex ID/);
assert.equal(collision.ctx.nodes.length,1,'a preceding safe vertex in the same response is not added on collision');
collision.ctx.nodes.length=0;
collision.ctx.show(null);
collision.ctx.show([differentObject]);
assert.equal(collision.ctx.graphTableServerForVertex(1),'lsst-server','replacing a cleared graph can reuse an ID');
const edgeFixture=fixture(true,[['ztf-server',ztf],['ztf-server',{type:'edge',id:3,outVid:1,inVid:1}]]);
edgeFixture.ctx.server='lsst-server';
assert.throws(()=>edgeFixture.ctx.show([{type:'edge',id:3,outVid:2,inVid:2}]),/Conflicting edge ID/);
assert.equal(edgeFixture.ctx.edges.length,1);
assert.throws(()=>edgeFixture.ctx.show([{type:'edge',id:4,outVid:1,inVid:2}]),/Conflicting edge endpoint/);
assert.equal(edgeFixture.ctx.edges.length,1);
const pendingEndpoint=fixture(true,[['ztf-server',ztf],['ztf-server',{type:'edge',id:4,outVid:1,inVid:2}]]);
pendingEndpoint.ctx.server='lsst-server';
assert.throws(()=>pendingEndpoint.ctx.show([lsst]),/Conflicting vertex ID|Conflicting edge endpoint/,
 'a previously unresolved edge endpoint reserves its vertex ID for its own server');
assert.equal(pendingEndpoint.ctx.nodes.length,1,'rejection preserves the existing vertex list');
assert.equal(pendingEndpoint.ctx.edges.length,1,'rejection preserves the existing edge list');
assert.equal(pendingEndpoint.ctx.graphTableServerForVertex(2),null,'rejection does not assign vertex origin');
const graphPage=fs.readFileSync(path.join(root,'webservice/GraphView.jsp'),'utf8');
assert.match(graphPage,/webservice\/graph-table-origin\.js\?v=/);
console.log('mixed ZTF/LSST object table routes each graph vertex to its own Gremlin server');
